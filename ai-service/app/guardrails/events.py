SEVERITY: dict[str, str] = {
    PROMPT_INJECTION_DIRECT: "HIGH",
    PROMPT_INJECTION_INDIRECT: "HIGH",
    SYSTEM_PROMPT_LEAK_ATTEMPT: "MEDIUM",
    ENCODED_INSTRUCTION: "HIGH",
    INPUT_TOO_LONG: "LOW",
    TOOL_NOT_ALLOWED: "HIGH",
    TOOL_CALL_LIMIT_EXCEEDED: "MEDIUM",
    PARAM_SCHEMA_VIOLATION: "MEDIUM",
    DENIED_PARAM_PRESENT: "HIGH",
    DOMAIN_NOT_ALLOWED: "HIGH",
    SIDE_EFFECT_CONFIRMATION_REQUIRED: "MEDIUM",
    PII_MASKED: "LOW",
    PII_LEAK_PREVENTED: "HIGH",
    OUTPUT_UNSAFE_HTML: "MEDIUM",
    OUTPUT_UNVERIFIED_URL: "LOW",
    OUTPUT_SYSTEM_PROMPT_LEAK: "HIGH",
    RATE_LIMITED: "LOW",
    TASK_TIMEOUT: "MEDIUM",
    METRICS_MISMATCH: "MEDIUM",
}


def severity_of(event_type: str) -> str:
    return SEVERITY.get(event_type, "MEDIUM")


