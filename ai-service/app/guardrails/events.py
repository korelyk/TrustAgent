# 平台侧
#: 任务超过策略允许的耗时上限（由 orchestrator 的 deadline 检查触发）。
#: 之前没有这个事件类型，因为超时控制本身没有实现（task_timeout_ms 从未被消费）。
TASK_TIMEOUT = "TASK_TIMEOUT"
RATE_LIMITED = "RATE_LIMITED"
